#!/usr/bin/env python3
"""Irbid Drive (Roblox): turn the vehicle database built by build_car_database.py into compact Roblox data.

  python tools/vehicle_catalog/build_car_database.py --out-dir tools/vehicle_catalog/generated
  python tools/vehicle_catalog/make_roblox_catalog.py tools/vehicle_catalog/generated/irbid_drive_vehicle_database.json

Writes roblox/catalog/ (packed into ReplicatedStorage.IrbidCatalog by tools/make_roblox.js):
  CatalogDict.lua    makes, fuels, gearboxes, drivetrains, counts, source + licence lines
  Catalog1..N.lua    the variants, one per line, tab-separated (see FIELDS); "" = not in the source (shown as Unknown)
  CarLinks.lua       each of the game's 217 cars -> the closest catalogue variant of the same make + model (or none)
  CAR_LINKS.md       the same links, for review
Source values are never changed; implausible ones are flagged (SUSPECT bits), not hidden or zeroed.
Exact duplicate source rows (same identity and the same numbers) are kept once.
"""
from __future__ import annotations
import importlib.util, json, math, re, sys, unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "roblox" / "catalog"
CHUNK = 240000  # characters per ModuleScript (as tools/make_roblox.js)
SPEC = ["fuel_type", "cylinders", "displacement_cc", "power_hp", "torque_nm", "transmission", "drivetrain", "acceleration_0_to_100_kmh_s",
        "top_speed_kmh", "fuel_economy_combined_l_100km", "length_mm", "width_mm", "height_mm", "wheelbase_mm", "curb_weight_kg"]
FIELDS = ["id", "make", "model", "generation", "year_start", "year_end", "engine"] + SPEC + ["suspect", "handling", "grip", "braking", "drift"]
# a value outside these ranges is flagged "suspect" (bit, field, low, high): wider than any production car we know of
SUSPECT = [(1, "power_hp", 20, 2100), (2, "torque_nm", 1, 4000), (4, "acceleration_0_to_100_kmh_s", 1.7, 60), (8, "top_speed_kmh", 40, 500),
           (16, "curb_weight_kg", 300, 8000), (32, "fuel_economy_combined_l_100km", 0.5, 60), (64, "length_mm", 1500, 8000),
           (64, "width_mm", 1000, 3000), (64, "height_mm", 800, 3500), (64, "wheelbase_mm", 1000, 5000), (128, "displacement_cc", 40, 10000)]
# generation codes in the game's car names -> production years of that generation (first model year of a catalogue generation must
# fall inside). Without this the nearest top speed / 0-100 can pick another generation (an MX-5 "NA" is 1989-1997, not the 2016 car).
GEN_YEARS = {"na": (1989, 1997), "e36": (1990, 1999), "z33": (2002, 2008), "mk7": (2012, 2020), "r34": (1998, 2002), "fd3s": (1991, 2002),
             "jza80": (1993, 2002), "r35": (2007, 2026), "w211": (2002, 2009), "w203": (2000, 2007), "w221": (2005, 2013), "e46": (1997, 2006),
             "e60": (2003, 2010), "g80": (2020, 2026), "g82": (2020, 2026), "mk5": (2019, 2026), "c8": (2019, 2026), "lc200": (2007, 2021),
             "foxbody": (1979, 1993), "lpi 800 4": (2021, 2022), "365 gtb 4": (1968, 1973), "w108": (1965, 1972)}
MAKE_ALIAS = {"range rover": "Land Rover", "vw": "Volkswagen", "mercedes": "Mercedes-Benz", "chevy": "Chevrolet", "alfa": "Alfa Romeo"}


def load_builder():
    spec = importlib.util.spec_from_file_location("builder", Path(__file__).with_name("build_car_database.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def num(v):
    if v is None:
        return ""
    if isinstance(v, float) and v.is_integer():
        v = int(v)
    return repr(v)


def txt(v):
    return "" if v is None else re.sub(r"[\t\r\n]+", " ", str(v)).strip()


def norm(s):
    s = unicodedata.normalize("NFKD", s.lower())
    s = "".join(c for c in s if not unicodedata.combining(c))
    return " ".join(re.sub(r"[-/_.,()]+", " ", s).split())


def suspect_bits(sp):
    bits = 0
    for b, f, lo, hi in SUSPECT:
        v = sp.get(f)
        if v is not None and not (lo <= v <= hi):
            bits |= b
    return bits


def game_cars():
    """(index, roblox name, web name, top km/h, 0-100 s) from roblox/CAR_NAMES.md + roblox/shared/Meta.lua (both generated by make_roblox.js)."""
    names = re.findall(r"^\| (\d+) \| ([^|]+) \| ([^|]+) \|", (ROOT / "roblox" / "CAR_NAMES.md").read_text(encoding="utf-8"), re.M)
    meta = (ROOT / "roblox" / "shared" / "Meta.lua").read_text(encoding="utf-8")
    specs = re.findall(r'\{name="([^"]+)",tier=.*?pt=\{vref=([-\d.e]+),aref=[-\d.e]+,t100=([-\d.e]+)', meta)
    if len(names) != len(specs):
        raise SystemExit(f"CAR_NAMES.md has {len(names)} cars, Meta.lua {len(specs)}: run tools/make_roblox.js first")
    out = []
    for (i, rn, wn), (mn, vref, t100) in zip(names, specs):
        if rn.strip() != mn:
            raise SystemExit(f"car {i}: {rn.strip()} in CAR_NAMES.md but {mn} in Meta.lua")
        out.append((int(i), rn.strip(), wn.strip(), float(vref) * 3.6, float(t100)))
    return out


def link_cars(rows, makes):
    """The closest variant of the same make + model by top speed and 0-100 (source values that are not suspect)."""
    by_make = {}
    for r in rows:
        by_make.setdefault(r["make"], []).append(r)
    mk_norm = sorted(((norm(m), m) for m in makes), key=lambda t: -len(t[0]))
    links = []
    for i, rn, wn, top, acc in game_cars():
        w = norm(wn)
        make, rest = None, ""
        for k, m in mk_norm:
            if w.startswith(k + " "):
                make, rest = m, w[len(k) + 1:]
                break
        if not make:
            for k, m in MAKE_ALIAS.items():
                if w.startswith(k + " "):
                    # "Range Rover Sport": the catalogue's Land Rover models start with "Range Rover"
                    make, rest = m, (w if m == "Land Rover" else w[len(k) + 1:])
                    break
        link = None
        if make and make in by_make:
            models, mk = {}, norm(make)
            for r in by_make[make]:
                models.setdefault(r["model"], []).append(r)

            # a catalogue model's names: "SKODA Octavia" -> "octavia", "ix35 / Tucson" -> "ix35", "tucson", "288 GTO/F40/F50/Enzo" -> ...
            def alts(m):
                out = set()
                for a in [m] + re.split(r"\s*/\s*", m):
                    a = norm(a)
                    if a.startswith(mk + " "):
                        a = a[len(mk) + 1:]
                    if a:
                        out.add(a)
                return out
            pad = " " + rest + " "
            hits = {}
            for m in models:
                ok = [a for a in alts(m) if (" " + a + " ") in pad]
                if ok:
                    hits[m] = max(ok, key=len)
            how = "model"
            if not hits:
                # "911" -> "911 Carrera 4", "911 GT3", ...: every model whose name starts with the game car's model words
                words = rest.split()
                for k in range(len(words), 0, -1):
                    pre = " ".join(words[:k])
                    for m in models:
                        ok = [a for a in alts(m) if a == pre or a.startswith(pre + " ")]
                        if ok:
                            hits[m] = pre
                    if hits:
                        break
                how = "models starting with"
            gen = next(((k, y) for k, y in GEN_YEARS.items() if (" " + k + " ") in (" " + w + " ")), None)
            if hits and not gen:
                best_len = max(len(a) for a in hits.values())
                hits = {m: a for m, a in hits.items() if len(a) == best_len}
            pool = [r for m in hits for r in models[m]]
            if gen:
                # a named generation: only variants whose generation starts in its years (every matched model, "Skyline" or "GT-R")
                pool = [r for r in pool if r["year_start"] and gen[1][0] - 1 <= r["year_start"] <= gen[1][1]]
                hits = {m: a for m, a in hits.items() if any(r["model"] == m for r in pool)}
                how = f"generation {gen[0].upper()} ({gen[1][0]}–{gen[1][1]}), {how}"
            # "Hybrid" / "EV" in the game car's name: prefer those versions when the model has them
            for word, fuel in (("hybrid", "hybrid"), ("ev", "electric")):
                if (" " + word + " ") in (" " + w + " "):
                    keep = [r for r in pool if fuel in (r["spec"]["fuel_type"] or "").lower()]
                    if keep:
                        pool = keep
                        hits = {m: a for m, a in hits.items() if any(r["model"] == m for r in pool)}
            # a model name that lists several cars ("288 GTO/F40/F50/Enzo/LaFerrari"): keep the generations named after the matched one
            named = [r for r in pool if (" " + hits[r["model"]] + " ") in (" " + norm(r["generation"] or "") + " ")]
            if named and len(named) < len(pool) and any("/" in m for m in hits):
                pool = named
            pool_models = list(hits)
            if pool:
                def score(r):
                    s, n = 0.0, 0
                    t, a = r["spec"]["top_speed_kmh"], r["spec"]["acceleration_0_to_100_kmh_s"]
                    if t is not None and not (r["suspect"] & 8):
                        s += abs(t - top) / top
                        n += 1
                    if a is not None and not (r["suspect"] & 4):
                        s += abs(a - acc) / acc
                        n += 1
                    return (s / n if n else 9.0, -(r["year_start"] or 0))
                best = min(pool, key=score)
                link = {"id": best["id"], "make": make, "model": best["model"], "pool": len(pool), "how": how,
                        "models": sorted({r["model"] for r in pool}), "score": score(best)[0], "row": best}
        links.append((i, rn, wn, top, acc, link))
    return links


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    src = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
    builder = load_builder()
    rows, seen, dropped = [], {}, 0
    for v in src["vehicles"]:
        ident, sp = v["identity"], v["real_world_specs"]
        key = json.dumps([ident, sp], sort_keys=True, ensure_ascii=False)
        if key in seen:
            dropped += 1
            continue
        seen[key] = True
        bits = suspect_bits(sp)
        # the builder's game estimates, with suspect source values left out (a 17,000-tonne "car" would otherwise score 35)
        est = builder.estimate_game_stats({
            "curb_weight_kg": None if bits & 16 else sp["curb_weight_kg"], "power_hp": None if bits & 1 else sp["power_hp"],
            "drivetrain": sp["drivetrain"], "body_type": ident["body_type"]})
        hid = v["id"].rsplit("-", 1)
        short = v["id"][-8:] if re.fullmatch(r"[0-9a-f]{8}", hid[-1]) else v["id"].rsplit("-", 2)[-2] + "-" + hid[-1]
        rows.append({"id": short, "make": ident["make"], "model": ident["model"], "generation": ident["generation"], "year_start": ident["year_start"],
                     "year_end": ident["year_end"], "engine": ident["engine_variant"], "spec": sp, "suspect": bits, "est": est})
    ids = [r["id"] for r in rows]
    if len(set(ids)) != len(ids):
        raise SystemExit("short ids collide: make them longer")
    rows.sort(key=lambda r: (norm(r["make"]), norm(r["model"]), r["year_start"] or 0, norm(r["generation"] or ""), norm(r["engine"] or "")))

    def dict_of(vals):
        return sorted({x for x in vals if x is not None}, key=norm)
    makes = dict_of(r["make"] for r in rows)
    fuels = dict_of(r["spec"]["fuel_type"] for r in rows)
    gears = dict_of(r["spec"]["transmission"] for r in rows)
    drives = dict_of(r["spec"]["drivetrain"] for r in rows)
    ix = lambda lst: {v: i + 1 for i, v in enumerate(lst)}
    mI, fI, gI, dI = ix(makes), ix(fuels), ix(gears), ix(drives)

    lines = []
    for r in rows:
        sp, e = r["spec"], r["est"]
        vals = [r["id"], str(mI[r["make"]]), txt(r["model"]), txt(r["generation"]), num(r["year_start"]), num(r["year_end"]), txt(r["engine"])]
        for f in SPEC:
            x = sp[f]
            vals.append(str(fI[x]) if f == "fuel_type" and x else str(gI[x]) if f == "transmission" and x else str(dI[x]) if f == "drivetrain" and x
                        else "" if f in ("fuel_type", "transmission", "drivetrain") else num(x))
        vals += [str(r["suspect"]), num(e["handling_score_0_100_estimate"]), num(e["grip_score_0_100_estimate"]),
                 num(e["braking_score_0_100_estimate"]), num(e["drift_suitability_0_100_estimate"])]
        assert len(vals) == len(FIELDS)
        lines.append("\t".join(vals))

    OUT.mkdir(parents=True, exist_ok=True)
    for f in OUT.glob("Catalog*.lua"):
        f.unlink()
    chunks, cur, n = [], [], 0
    for ln in lines:
        if cur and n + len(ln) + 1 > CHUNK:
            chunks.append(cur)
            cur, n = [], 0
        cur.append(ln)
        n += len(ln) + 1
    chunks.append(cur)
    for k, c in enumerate(chunks, 1):
        body = "\n".join(c)
        if "]==]" in body:
            raise SystemExit("a row contains ]==]")
        (OUT / f"Catalog{k}.lua").write_text("return [==[\n" + body + "\n]==]\n", encoding="utf-8", newline="\n")

    def lua_list(lst):
        return "{" + ",".join(json.dumps(x, ensure_ascii=False) for x in lst) + "}"
    meta_src = src["sources"][0]
    dict_lua = ("-- generated by tools/vehicle_catalog/make_roblox_catalog.py (do not edit)\nreturn {\n"
                f"\tcount = {len(rows)}, chunks = {len(chunks)}, generated = {json.dumps(src['generated_at_utc'], ensure_ascii=False)},\n"
                f"\tsourceRows = {src['vehicle_record_count']}, duplicatesDropped = {dropped},\n"
                f"\tfields = {lua_list(FIELDS)},\n\tmakes = {lua_list(makes)},\n\tfuels = {lua_list(fuels)},\n\tgears = {lua_list(gears)},\n\tdrives = {lua_list(drives)},\n"
                f"\tsuspect = {{{','.join('{%d,%s,%s,%s}' % (b, json.dumps(f, ensure_ascii=False), num(lo), num(hi)) for b, f, lo, hi in SUSPECT)}}},\n"
                f"\tsource = {json.dumps(meta_src['repository'], ensure_ascii=False)},\n"
                "\tcredit = \"Vehicle data: vehicle-makes-models (github.com/gor3a/vehicle-makes-models) and autoevolution.com, ODbL 1.0. Changed for Irbid Drive: duplicates removed, implausible values flagged, game estimates added.\",\n"
                f"\testimate = {json.dumps(src['vehicles'][0]['game_tuning_estimates']['estimate_method'] + ' Suspect source values are left out.', ensure_ascii=False)},\n"
                "}\n")
    (OUT / "CatalogDict.lua").write_text(dict_lua, encoding="utf-8", newline="\n")

    links = link_cars(rows, makes)
    lk = ["-- generated by tools/vehicle_catalog/make_roblox_catalog.py (do not edit): game car index -> closest catalogue variant (same make + model)",
          "-- id = the variant, models = the catalogue models it was chosen from, how = \"model\" (the same model name) or \"models starting with\"", "return {"]
    md = ["# Game cars → vehicle catalogue", "", "Generated by `tools/vehicle_catalog/make_roblox_catalog.py` (do not edit). Each game car is linked to the catalogue variant of the",
          "same make and model whose top speed and 0–100 km/h are closest to the game car's (the game's numbers are the web game's estimates, not",
          "these). A link is a reference, not a claim that the game car is that exact variant. \"—\" = no catalogue model of that make and name.", "",
          "| # | Roblox name | Web game car | Linked catalogue variant | Years | Top km/h game / source | 0–100 s game / source | Chosen from |", "|---|---|---|---|---|---|---|---|"]
    linked = 0
    for i, rn, wn, top, acc, L in links:
        if not L:
            lk.append(f"\t[{i}] = false,")
            md.append(f"| {i} | {rn} | {wn} | — | | {top:.0f} / | {acc:g} / | |")
            continue
        linked += 1
        r = L["row"]
        lk.append(f"\t[{i}] = {{ id = {json.dumps(L['id'], ensure_ascii=False)}, how = {json.dumps(L['how'], ensure_ascii=False)}, models = {lua_list(L['models'])} }},")
        yrs = f"{r['year_start'] or '?'}–{r['year_end'] or ''}"
        ms = ", ".join(L["models"][:4]) + (f" (+{len(L['models']) - 4})" if len(L["models"]) > 4 else "")
        md.append(f"| {i} | {rn} | {wn} | {r['make']} {r['generation']} · {r['engine']} | {yrs} | {top:.0f} / {num(r['spec']['top_speed_kmh']) or '?'} |"
                  f" {acc:g} / {num(r['spec']['acceleration_0_to_100_kmh_s']) or '?'} | {L['how']}: {ms} ({L['pool']} variants) |")
    lk.append("}")
    (OUT / "CarLinks.lua").write_text("\n".join(lk) + "\n", encoding="utf-8", newline="\n")
    (OUT / "CAR_LINKS.md").write_text("\n".join(md) + "\n", encoding="utf-8", newline="\n")

    flagged = sum(1 for r in rows if r["suspect"])
    print(f"variants {len(rows)} (source rows {src['vehicle_record_count']}, exact duplicates dropped {dropped}) | makes {len(makes)} | "
          f"fuels {len(fuels)} gearboxes {len(gears)} drivetrains {len(drives)} | modules {len(chunks)} ({sum(len(l) + 1 for l in lines):,} chars) | "
          f"rows with a suspect value {flagged} | game cars linked {linked}/{len(links)}")
    for b, f, lo, hi in SUSPECT:
        k = sum(1 for r in rows if r["spec"][f] is not None and not (lo <= r["spec"][f] <= hi))
        if k:
            print(f"  suspect {f}: {k} (outside {lo}..{hi})")


if __name__ == "__main__":
    main()
