#!/usr/bin/env python3
"""srtm_1km.json -> src/parts/03d_terrain_data.js (GENERATED). usage: python3 osm/terrain/gen_terrain.py (from project root)"""
import json,os
H=os.path.dirname(os.path.abspath(__file__))
d=json.load(open(os.path.join(H,'srtm_1km.json')));g=d['grid']
flat=[int(round(v)) for row in d['elev_m'] for v in row]
js=('// GENERATED by osm/terrain/gen_terrain.py -- do not edit.\n'
 '// Elevation: SRTM v3 1 arc-second (NASA/USGS) sampled on a %d m grid via OpenTopoData, retrieved %s. Absolute vertical accuracy spec <16 m (90%%).\n'
 '// Grid origin (x0,z0) in game metres (x=east, z=-north), row 0 = north. Heights are metres above sea level; the game subtracts T0 (height at the game origin).\n'
 'const TERR={x0:%r,z0:%r,s:%d,nx:%d,nz:%d,e:[%s]};\n')%(g['step'],d['retrieved'],g['x0'],g['z0'],g['step'],g['nx'],g['nz'],','.join(map(str,flat)))
out=os.path.join(H,'..','..','src','parts','03d_terrain_data.js');open(out,'w').write(js);print('wrote',out,len(js),'bytes')
